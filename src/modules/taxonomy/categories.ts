export class TaxonomyService {
  private static readonly categoriesById = new Map<string, CategoryDefinition>(
    TAXONOMY_CATEGORIES.map((c) => [c.id, c])
  );

  /**
   * Return all defined categories in the taxonomy.
   */
  public static getAllCategories(): readonly CategoryDefinition[] {
    return TAXONOMY_CATEGORIES;
  }

  /**
   * Lookup a category definition by its slug ID.
   */
  public static getById(id: string): CategoryDefinition | undefined {
    return this.categoriesById.get(id.toLowerCase());
  }

  /**
   * Determine if a category has an active, verified mapping.
   */
  public static isSupported(id: string): boolean {
    const cat = this.getById(id);
    return cat ? cat.isSupported : false;
  }

  /**
   * Return the semantic tokens for a category.
   */
  public static getSemanticTerms(categoryId: string): readonly string[] {
    const cat = this.getById(categoryId);
    return cat?.semanticTerms ?? [];
  }

  /**
   * Check whether an icon name strictly matches a category's semantic definition.
   * Enforces exact token-boundary matching: matches whole hyphen/underscore/colon-delimited tokens.
   * Strictly prevents substring collisions inside unrelated words (e.g. 'play' inside 'display',
   * or 'right' inside 'copyright'), while preserving valid compound icon names like
   * 'arrow-right', 'turn-right', 'move-right', and 'display-play'.
   */
  public static matchesCategory(iconName: string, categoryId: string): boolean {
    const cleanCat = categoryId.toLowerCase();
    if (cleanCat === 'all') return true;

    const cat = this.getById(cleanCat);
    if (!cat) return false;

    // If category has semantic terms, icon name must contain at least one term at token boundaries
    if (cat.semanticTerms && cat.semanticTerms.length > 0) {
      // Normalize icon name into token-boundary delimited format: '-token1-token2-'
      const normalizedName = `-${iconName.toLowerCase().replace(/[^a-z0-9]+/g, '-')}-`;

      return cat.semanticTerms.some((term) => {
        // Normalize term into token-boundary delimited format: '-term-'
        const normalizedTerm = `-${term.toLowerCase().replace(/[^a-z0-9]+/g, '-')}-`;
        return normalizedName.includes(normalizedTerm);
      });
    }

    return true;
  }
}
